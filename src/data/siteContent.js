/** Retourne { routineId?, productIds[], bundleId?, title, description } */
export function getQuizRecommendation(answers, locale = 'fr') {
  const { zone, concern, moment } = answers

  if (concern === 'maternity') {
    return {
      bundleId: 'mama-bear',
      productIds: [],
      title: locale === 'fr' ? 'Coffret Mama Bear' : 'Mama Bear set',
      description:
        locale === 'fr'
          ? 'Dry Oil le matin, COMFY & Relief Balm le soir — rituel maternité complet.'
          : 'Dry Oil morning, COMFY & Relief Balm evening — complete maternity ritual.',
    }
  }

  if (zone === 'travel' || moment === 'anytime') {
    return {
      routineId: null,
      productIds: ['glow-and-go', 'safaa', 'soft-kiss'],
      title: locale === 'fr' ? 'Essentiels nomades' : 'Travel essentials',
      description:
        locale === 'fr'
          ? 'Perles multi-usages, savon purifiant et baume lèvres — partout avec vous.'
          : 'Multi-use pearls, purifying soap and lip balm — anywhere with you.',
    }
  }

  if (concern === 'feet') {
    return {
      routineId: 'pieds',
      productIds: ['comfy'],
      title: locale === 'fr' ? 'Rituel pieds' : 'Foot ritual',
      description: locale === 'fr' ? 'Galettes fondantes pour des pieds doux.' : 'Melting wafers for soft feet.',
    }
  }

  if (concern === 'blemish' && (moment === 'night' || zone === 'face')) {
    return {
      routineId: 'double-nettoyage',
      productIds: ['nurture', 'safaa', 'fix-it'],
      title: locale === 'fr' ? 'Peau clarifiée' : 'Clarified skin',
      description:
        locale === 'fr'
          ? 'Double nettoyage + soin ciblé imperfections.'
          : 'Double cleanse + targeted blemish care.',
    }
  }

  if (moment === 'weekly') {
    return {
      routineId: 'hebdo',
      productIds: ['aura'],
      title: locale === 'fr' ? 'Exfoliation hebdo' : 'Weekly exfoliation',
      description: locale === 'fr' ? 'Gommage fouetté AURA en douceur.' : 'Gentle AURA whipped polish.',
    }
  }

  if (moment === 'night' || concern === 'dry') {
    if (zone === 'body' || zone === 'both') {
      return {
        routineId: 'corps',
        productIds: ['shiny', 'cocoony'],
        title: locale === 'fr' ? 'Corps nourri' : 'Nourished body',
        description: locale === 'fr' ? 'Lait éclat + crème fouettée cocooning.' : 'Radiance milk + cocooning whipped cream.',
      }
    }
    return {
      routineId: 'nuit',
      productIds: ['nurture', 'noor'],
      title: locale === 'fr' ? 'Nuit réparatrice' : 'Repairing night',
      description: locale === 'fr' ? 'Démaquillage doux + crème NOOR.' : 'Gentle cleanse + NOOR night cream.',
    }
  }

  if (zone === 'body') {
    return {
      routineId: 'corps',
      productIds: ['shiny', 'cocoony'],
      title: locale === 'fr' ? 'Corps éclat' : 'Body glow',
      description: locale === 'fr' ? 'Hydratation et nutrition veloutée.' : 'Hydration and velvety nourishment.',
    }
  }

  return {
    routineId: 'matin-eclat',
    productIds: ['safaa', 'shiny', 'sunsafe'],
    title: locale === 'fr' ? 'Matin éclat' : 'Morning glow',
    description: locale === 'fr' ? 'Nettoyer · Hydrater · Protéger (SPF50+).' : 'Cleanse · Hydrate · Protect (SPF50+).',
  }
}
